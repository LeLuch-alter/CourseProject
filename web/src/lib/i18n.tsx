const dicts: Record<Lang, Dict> = { ru, kk, en }

export function translate(lang: Lang, key: string, ...args: Array<string | number>): string {
  let s = dicts[lang][key] ?? dicts.ru[key] ?? key
  args.forEach((a, i) => {
    s = s.replace(`{${i}}`, String(a))
  })
  return s
}

export function fill(template: string, values: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => values[k] ?? '')
}

interface I18nCtx {
  lang: Lang
  locale: string
  setLang: (l: Lang) => void
  t: (key: string, ...args: Array<string | number>) => string
}
const Ctx = createContext<I18nCtx | null>(null)

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('kvit.lang') as Lang | null
    if (saved && LANGS.includes(saved)) return saved
  } catch {
    /* storage unavailable */
  }
  const nav = navigator.language.slice(0, 2)
  return nav === 'kk' ? 'kk' : nav === 'en' ? 'en' : 'ru'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang)
  const value = useMemo<I18nCtx>(
    () => ({
      lang,
      locale: LOCALES[lang],
      setLang: (l) => {
        setLangState(l)
        try {
          localStorage.setItem('kvit.lang', l)
        } catch {
          /* ignore */
        }
        document.documentElement.lang = l
      },
      t: (key, ...args) => translate(lang, key, ...args),
    }),
    [lang],
  )
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n(): I18nCtx {
  const v = useContext(Ctx)
  if (!v) throw new Error('useI18n outside provider')
  return v
}
